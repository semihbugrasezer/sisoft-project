    "cümlede aday öznesini tekrar arama. Quote kriterin tersini açıkça söylüyorsa contradicts; "
    "yalnız konusal kelime benzerliği varsa veya destek için ek varsayım gerekiyorsa irrelevant "
    "seç. Eksik süre, kıdem, yeterlilik, nedensellik veya sonuç uydurma. evidenceId değerini "
